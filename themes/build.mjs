#!/usr/bin/env node
// Builds every theme in this directory (any folder with a theme.json) into <theme>/dist/.
//
//   node themes/build.mjs                    build all themes
//   node themes/build.mjs vitesse            build one
//   node themes/build.mjs --explain vitesse dark-soft
//                                            print each palette role, its color, and which
//                                            VS Code key/scope it came from
//
// See README.md for the theme.json format and the workflow for adding a theme.

import { existsSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import { dirname, join, relative } from 'node:path'
import { fileURLToPath } from 'node:url'
import { buildPalette, ROLES } from './lib/palette.mjs'
import { loadVscodeTheme, parseJsonc } from './lib/vscode.mjs'
import { isZedTheme, zedToVscode } from './lib/zed.mjs'

import bat from './lib/targets/bat.mjs'
import btop from './lib/targets/btop.mjs'
import delta from './lib/targets/delta.mjs'
import ghostty from './lib/targets/ghostty.mjs'
import helix from './lib/targets/helix.mjs'
import leaf from './lib/targets/leaf.mjs'
import starship from './lib/targets/starship.mjs'
import vivid from './lib/targets/vivid.mjs'
import zsh from './lib/targets/zsh.mjs'

// A target has `files(palette, ctx)` for per-variant files and/or `combined(variants, ctx)`
// for one file covering every variant (config snippets). Both return [{ path, content }]
// with paths relative to dist/.
const TARGETS = [ghostty, bat, delta, helix, btop, starship, leaf, vivid, zsh]

const ROOT = dirname(fileURLToPath(import.meta.url))

function fail(msg) {
  console.error(`error: ${msg}`)
  process.exit(1)
}

function loadTheme(slug) {
  const dir = join(ROOT, slug)
  const manifestPath = join(dir, 'theme.json')
  if (!existsSync(manifestPath))
    fail(`${relative(process.cwd(), manifestPath)} not found`)
  const theme = JSON.parse(readFileSync(manifestPath, 'utf8'))
  theme.slug = slug
  theme.dir = dir

  if (!/^[a-z0-9-]+$/.test(slug))
    fail(`theme folder "${slug}" must be lowercase letters, digits and dashes`)
  if (!theme.name || !theme.variants || !Object.keys(theme.variants).length)
    fail(`${slug}/theme.json needs "name" and at least one entry in "variants"`)

  for (const [id, v] of Object.entries(theme.variants)) {
    if (!/^[a-z0-9-]+$/.test(id))
      fail(`${slug}: variant id "${id}" must be lowercase letters, digits and dashes`)
    if (!v.name || !v.file)
      fail(`${slug}: variant "${id}" needs "name" and "file"`)
    if (!existsSync(join(dir, v.file)))
      fail(`${slug}: variant "${id}" file ${v.file} not found`)
  }
  for (const [pair, modes] of Object.entries(theme.pairs ?? {})) {
    if (!/^[a-z0-9_]+$/.test(pair))
      fail(`${slug}: pair name "${pair}" must be lowercase letters, digits and underscores`)
    if (pair === 'build' || pair === 'clean')
      fail(`${slug}: pair name "${pair}" is reserved by try.sh`)
    for (const mode of ['dark', 'light']) {
      if (!theme.variants[modes[mode]])
        fail(`${slug}: pair "${pair}".${mode} = "${modes[mode]}" is not a variant`)
    }
  }
  if (theme.defaultPair && !theme.pairs?.[theme.defaultPair])
    fail(`${slug}: defaultPair "${theme.defaultPair}" is not in "pairs"`)

  const knownRoles = new Set(Object.keys(ROLES))
  const checkOverrides = (o, where) => {
    for (const role of Object.keys(o ?? {})) {
      if (!knownRoles.has(role) && !role.startsWith('ansi.'))
        fail(`${slug}: ${where} overrides unknown role "${role}" (see lib/palette.mjs)`)
    }
  }
  checkOverrides(theme.overrides, 'theme')
  for (const [id, v] of Object.entries(theme.variants)) checkOverrides(v.overrides, `variant "${id}"`)

  return theme
}

// A variant's file is a VS Code theme or a Zed theme family (lib/zed.mjs translates the
// latter into the former). `theme` picks one theme out of a Zed family; it defaults to the
// variant's display name.
function loadSource(file, v) {
  const json = parseJsonc(readFileSync(file, 'utf8'))
  return isZedTheme(json) ? zedToVscode(json, file, v.theme ?? v.name) : loadVscodeTheme(file)
}

function variantsOf(theme) {
  return Object.entries(theme.variants).map(([id, v]) => {
    let vscode, p
    try {
      vscode = loadSource(join(theme.dir, v.file), v)
      p = buildPalette(vscode, { overrides: { ...theme.overrides, ...v.overrides }, mode: v.mode })
    }
    catch (e) {
      fail(`${theme.slug} / ${id} (${v.file}): ${e.message}`)
    }
    const stem = `${theme.slug}-${id}`
    return { id, variant: { id, ...v }, vscode, p, stem, stemUs: stem.replaceAll('-', '_') }
  })
}

function headerFor(theme, variantName) {
  const src = theme.source?.url ? ` from ${theme.source.url}` : ''
  return `${variantName ?? theme.name}. Generated by themes/build.mjs${src} — do not edit by hand.`
}

// Shell-readable description of the theme, used by try.sh and the `theme` function.
function pairsFile(theme, variants) {
  const q = s => `'${String(s).replaceAll('\'', '\'\\\'\'')}'`
  const lines = [
    '# Generated by themes/build.mjs — do not edit by hand.',
    `THEME_SLUG=${q(theme.slug)}`,
    `THEME_NAME=${q(theme.name)}`,
    `THEME_PAIRS=${q(Object.keys(theme.pairs ?? {}).join(' '))}`,
    `THEME_DEFAULT_PAIR=${q(theme.defaultPair ?? Object.keys(theme.pairs ?? {})[0] ?? '')}`,
  ]
  for (const [pair, modes] of Object.entries(theme.pairs ?? {})) {
    lines.push(`THEME_PAIR_${pair}_dark=${q(`${theme.slug}-${modes.dark}`)}`)
    lines.push(`THEME_PAIR_${pair}_light=${q(`${theme.slug}-${modes.light}`)}`)
  }
  for (const v of variants)
    lines.push(`THEME_NAME_${v.stemUs}=${q(v.variant.name)}`)
  return `${lines.join('\n')}\n`
}

function build(slug) {
  const theme = loadTheme(slug)
  const variants = variantsOf(theme)
  const dist = join(theme.dir, 'dist')
  rmSync(dist, { recursive: true, force: true })

  const out = []
  for (const target of TARGETS) {
    for (const v of variants) {
      if (!target.files)
        continue
      const text = headerFor(theme, v.variant.name)
      out.push(...target.files(v.p, {
        theme,
        vscode: v.vscode,
        variant: v.variant,
        stem: v.stem,
        stemUs: v.stemUs,
        headerText: text,
        header: c => `${c} ${text}`,
      }))
    }
    if (target.combined)
      out.push(...target.combined(variants, { theme }))
  }
  out.push({ path: 'pairs.sh', content: pairsFile(theme, variants) })

  console.log(`${theme.name} -> ${relative(process.cwd(), dist)}/`)
  for (const { path, content } of out) {
    const file = join(dist, path)
    mkdirSync(dirname(file), { recursive: true })
    writeFileSync(file, content.endsWith('\n') ? content : `${content}\n`)
    console.log(`  ${path}`)
  }
}

function explain(slug, id) {
  const theme = loadTheme(slug)
  const variants = variantsOf(theme).filter(v => !id || v.id === id)
  if (!variants.length)
    fail(`${slug} has no variant "${id}"`)
  for (const { id, p } of variants) {
    console.log(`\n${theme.name} / ${id} (${p.mode})`)
    const rows = [...Object.keys(ROLES).map(r => [r, p[r]]), ...Object.entries(p.ansi).map(([k, v]) => [`ansi.${k}`, v])]
    for (const [role, color] of rows) {
      const src = p.sources[role] ?? '(none)'
      const style = p.fontStyle[role] ? ` [${p.fontStyle[role]}]` : ''
      const flag = /^#/.test(src) ? '   <- placeholder, theme has no color for this: consider an override' : ''
      console.log(`  ${role.padEnd(20)} ${String(color ?? '-').padEnd(8)} ${src}${style}${flag}`)
    }
  }
}

const args = process.argv.slice(2)
if (args[0] === '--explain') {
  if (!args[1])
    fail('usage: build.mjs --explain <theme> [variant]')
  explain(args[1], args[2])
}
else {
  const slugs = args.length
    ? args
    : readdirSync(ROOT, { withFileTypes: true })
        .filter(d => d.isDirectory() && existsSync(join(ROOT, d.name, 'theme.json')))
        .map(d => d.name)
  if (!slugs.length)
    fail('no themes found (folders with a theme.json)')
  slugs.forEach(build)
}
