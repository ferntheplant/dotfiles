// starship palettes, collected into a snippet to append to starship.toml.
//
// The palette redefines the ANSI color names (red, green, ..., purple = magenta) because the
// prompt modules are styled with those names ("bold green"). That makes the prompt use the
// theme's exact colors instead of whatever the terminal's ANSI slots hold.

export default {
  name: 'starship',
  combined(variants, { theme }) {
    const body = variants.map(({ p, stem }) => `[palettes.${stem}]
black = '${p.ansi.black}'
red = '${p.red}'
green = '${p.green}'
yellow = '${p.yellow}'
blue = '${p.blue}'
purple = '${p.magenta}'
cyan = '${p.cyan}'
white = '${p.ansi.white}'
bright-black = '${p.ansi.brightBlack}'
primary = '${p.primary}'
orange = '${p.orange}'
comment = '${p.comment}'
muted = '${p.fgSecondary}'
`).join('\n')
    return [{
      path: 'snippets/starship-palettes.toml',
      content: `# ${theme.name} starship palettes. Generated by themes/build.mjs — do not edit by hand.
# Append to starship.toml and set: palette = "<one of the names below>"

${body}`,
    }]
  },
}
