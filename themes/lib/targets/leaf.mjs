// leaf (terminal markdown viewer) themes, collected into a snippet for leaf/config.toml.
//
// leaf can only highlight code blocks with its built-in syntect themes, so `base`/`syntax`
// are picked by mode. Everything else follows the theme's markdown scopes (heading, quote,
// raw, list marker, links) and uses the palette for leaf's chrome (TOC, status bar).

export default {
  name: 'leaf',
  combined(variants, { theme }) {
    const body = variants.map(({ p, stem }) => {
      const ui = {
        toc_bg: p.bg,
        toc_border: p.muted,
        content_bg: p.bg,
        scrollbar_hover: p.muted,
        status_bg: p.bg,
        status_separator: p.muted,
        status_brand_fg: p.bg,
        status_brand_bg: p.primary,
        status_filename_fg: p.fgActive,
        status_filename_bg: p.bgActive,
        status_watch_fg: p.bg,
        status_watch_bg: p.cyan,
        status_reloaded_fg: p.bg,
        status_reloaded_bg: p.cyan,
        status_search_fg: p.yellow,
        status_search_bg: p.bgActive,
        status_success_fg: p.bg,
        status_success_bg: p.green,
        status_warning_fg: p.warning,
        status_error_fg: p.error,
        status_error_bg: p.bgActive,
        status_shortcut_fg: p.fgSecondary,
        status_percent_fg: p.primary,
        toc_hover_fg: p.fg,
        toc_header_fg: p.fgActive,
        toc_active_bg: p.lineHighlight,
        toc_inactive_bg: p.bg,
        toc_accent: p.primary,
        toc_index_inactive: p.fgSecondary,
        toc_primary_active: p.fg,
        toc_primary_inactive: p.fgActive,
        toc_secondary_inactive: p.fgSecondary,
        toc_secondary_text_active: p.fg,
        toc_secondary_text_inactive: p.fgActive,
      }
      const md = {
        search_highlight_bg: p.findMatchHighlight,
        search_match_bg: p.yellow,
        code_gutter: p.lineNr,
        blockquote_marker: p.muted,
        list_level_1: p.listMarker,
        list_level_2: p.fgSecondary,
        list_level_3: p.muted,
        ordered_list: p.listMarker,
        table_border: p.muted,
        table_separator: p.bgActive,
        table_header: p.heading,
        table_cell: p.fg,
        heading_1: p.heading,
        heading_2: p.heading,
        heading_3: p.heading,
        heading_4: p.heading,
        heading_other: p.heading,
        heading_underline: p.muted,
        code_frame: p.muted,
        code_label: p.fgSecondary,
        inline_code_fg: p.raw,
        inline_code_bg: p.bgActive,
        rule: p.muted,
        link_icon: p.linkUrl,
        link_text: p.linkText,
        link_hover: p.constant,
        blockquote_text: p.quote,
        text: p.fg,
        strong_text: p.fg,
        latex_inline_fg: p.number,
        latex_inline_bg: p.bgActive,
        latex_block_fg: p.number,
        mermaid_keyword: p.keyword,
        mermaid_arrow: p.operator,
        mermaid_label: p.string,
        mermaid_block_fg: p.fg,
        mark_fg: p.bg,
        mark_bg: p.yellow,
        task_checked: p.green,
        task_unchecked: p.muted,
        alert_note: p.blue,
        alert_tip: p.green,
        alert_important: p.magenta,
        alert_warning: p.warning,
        alert_caution: p.error,
      }
      const kv = o => Object.entries(o).map(([k, v]) => `${k} = "${v}"`).join('\n')
      return `[themes.${stem}]
base = "${p.isDark ? 'ocean' : 'arctic'}"
syntax = "${p.isDark ? 'base16-ocean.dark' : 'base16-ocean.light'}"

[themes.${stem}.ui]
${kv(ui)}

[themes.${stem}.markdown]
${kv(md)}
`
    }).join('\n')
    return [{
      path: 'snippets/leaf-themes.toml',
      content: `# ${theme.name} leaf themes. Generated by themes/build.mjs — do not edit by hand.
# Append to leaf/config.toml and set: theme = "<one of the names below>"

${body}`,
    }]
  },
}
