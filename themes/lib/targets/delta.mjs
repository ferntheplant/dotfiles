// delta — one [delta "<stem>"] feature per variant, collected into a gitconfig snippet.
//
// - syntax-theme is the bat theme from bat.mjs (so it needs `bat cache --build`).
// - Emphasised (changed-word) backgrounds are the theme's diffEditor text backgrounds. The
//   whole-line backgrounds are a lighter tint of red/green (15% dark, 10–12% light), because
//   VS Code themes rarely define a separate line color that reads well in a terminal.
// - map-styles tint moved lines (delta's color-moved support) at 25%.

import { mix } from '../color.mjs'

export default {
  name: 'delta',
  combined(variants, { theme }) {
    const body = variants.map(({ p, stem }) => {
      const plus = p.diffInserted ?? mix(p.green, p.bg, 0.3)
      const minus = p.diffRemoved ?? mix(p.red, p.bg, 0.3)
      return `[delta "${stem}"]
\t${p.mode} = true
\tsyntax-theme = ${stem}
\tblame-palette = "${p.bg} ${p.bgActive} ${p.lineHighlight} ${p.selection}"
\tcommit-decoration-style = box ul
\tfile-style = "${p.fg}"
\tfile-decoration-style = "${p.fg}"
\thunk-header-decoration-style = box ul
\thunk-header-file-style = bold
\thunk-header-line-number-style = bold "${p.fgSecondary}"
\thunk-header-style = file line-number syntax
\tline-numbers-left-style = "${p.lineNr}"
\tline-numbers-right-style = "${p.lineNr}"
\tline-numbers-zero-style = "${p.lineNr}"
\tline-numbers-minus-style = bold "${p.red}"
\tline-numbers-plus-style = bold "${p.green}"
\tminus-emph-style = bold syntax "${minus}"
\tminus-style = syntax "${mix(p.red, p.bg, p.isDark ? 0.15 : 0.12)}"
\tplus-emph-style = bold syntax "${plus}"
\tplus-style = syntax "${mix(p.green, p.bg, p.isDark ? 0.15 : 0.1)}"
\tmap-styles = \\
\t\tbold purple => syntax "${mix(p.magenta, p.bg, 0.25)}", \\
\t\tbold blue => syntax "${mix(p.blue, p.bg, 0.25)}", \\
\t\tbold cyan => syntax "${mix(p.cyan, p.bg, 0.25)}", \\
\t\tbold yellow => syntax "${mix(p.yellow, p.bg, 0.25)}"
`
    }).join('\n')
    return [{
      path: 'snippets/delta.gitconfig',
      content: `# ${theme.name} delta features. Generated by themes/build.mjs — do not edit by hand.
# [include] this file, then set [delta] features = <one of the names below>.
# Requires the matching bat themes (syntax-theme), installed and cached with \`bat cache --build\`.

${body}`,
    }]
  },
}
